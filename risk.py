"""Риск-модель: риск на позицию, масштабируемый от корреляции портфеля.

Размер риска на позицию зависит от взвешенной корреляции портфеля: при высокой
концентрации риск режется, при диверсификации — повышается. Список упорядочен по
убыванию верхней границы корреляции; выбирается ПЕРВЫЙ интервал, в который
попадает corr (т.е. верхняя граница >= corr).
"""
# (верхняя граница корреляции, риск на позицию в долях капитала).
# Упорядочено по ВОЗРАСТАНИЮ верхней границы; искомая полоса — первая, чей
# верхний предел >= corr (т.е. corr попадает строго под этот предел и выше
# предыдущего). Шкала: выше корреляция -> ниже риск.
RISK_BY_CORR = [
    (0.20, 0.025),   # corr <= +0.20 — сверхдиверсифицировано: можно больше
    (0.35, 0.020),   # +0.20..+0.35 — нейтрально
    (0.55, 0.020),   # +0.35..+0.55 — «хорошая» зона: базис 2%
    (0.70, 0.015),   # +0.55..+0.70 — повышенный риск
    (1.00, 0.010),   # corr > +0.70 — высокая концентрация: самый низкий риск
]

RR = 2.0  # соотношение TP:SL (1:2)


def risk_pct_for_corr(corr):
    """Риск на позицию (доля капитала) для текущей корреляции портфеля."""
    for bound, risk in RISK_BY_CORR:
        if corr <= bound:
            return risk
    return RISK_BY_CORR[-1][1]
